import {PGlite} from '@electric-sql/pglite';
import {readFile,readdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
try{
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
 create schema auth;create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 grant usage on schema public,auth to anon,authenticated,service_role;grant execute on function auth.uid() to authenticated;`);
 for(const file of (await readdir('supabase/migrations')).filter(f=>f.endsWith('.sql')).sort())await db.exec(await readFile('supabase/migrations/'+file,'utf8'));
 const id=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
 const project=id(1),other=id(2),profile=id(3),credential=id(4),experiment=id(5),attempt=id(6),owner=id(7),stranger=id(8),second=id(9);
 await db.query(`insert into monitor_projects(id,name) values($1,'main'),($2,'other')`,[project,other]);
 await db.query(`insert into project_members values($1,$2,'owner')`,[project,owner]);
 await db.query(`insert into source_profiles(project_id,id,label) values($1,$2,'wice')`,[project,profile]);
 await db.query(`insert into upload_credentials(id,project_id,profile_id,token_hash,label,expires_at) values($1,$2,$3,'hash','test',now()+interval '1 day')`,[credential,project,profile]);
 let sequence=0;
 const event=(kind,payload,aid=attempt)=>({event_id:crypto.randomUUID(),experiment_id:experiment,attempt_id:aid,sequence:++sequence,kind,observed_at:new Date().toISOString(),payload});
 const ingest=async events=>(await db.query('select monitor_ingest($1,$2::jsonb) as receipt',[credential,JSON.stringify(events)])).rows[0].receipt;
 const registered=event('experiment_registered',{model:'sta2',configuration:{seed:42}});
 const started=event('attempt_started',{job_id:'123',cluster:'wice'});
 const first=await ingest([registered,started]);assert.equal(first.accepted.length,2);
 const replay=await ingest([registered,started]);assert.equal(replay.duplicates.length,2);
 await assert.rejects(()=>ingest([{...registered,payload:{model:'gru'}}]),/event_conflict/);
 const epoch=n=>event('epoch_committed',{epoch:n,history_revision:attempt,action_mt5r:n/10});
 await ingest([epoch(1),epoch(2),epoch(3)]);
 const count=()=>db.query('select count(*)::int as n from ingest_receipts');
 const before=(await count()).rows[0].n;
 await assert.rejects(()=>ingest([event('progress',{phase:'training'}),event('resume_confirmed',{parent_attempt_id:id(99),cutoff:1},second)]),/parent_not_registered/);
 assert.equal((await count()).rows[0].n,before,'invalid batch must roll back earlier writes');
 await ingest([event('experiment_registered',{model:'sta2'},second),event('attempt_started',{job_id:'124'},second),event('resume_confirmed',{parent_attempt_id:attempt,cutoff:1},second),event('epoch_committed',{epoch:2,history_revision:second,action_mt5r:0.4},second)]);
 const history=(await db.query('select * from monitor_history($1,$2)',[project,experiment])).rows;
 assert.deepEqual(history.map(r=>r.epoch),[1,2]);assert.equal(history[1].metrics.action_mt5r,0.4);
 await ingest([epoch(4)]); // late parent observation must not resurrect epoch 4
 assert.deepEqual((await db.query('select epoch from monitor_history($1,$2)',[project,experiment])).rows.map(r=>r.epoch),[1,2]);
 await db.exec(`set role anon`);
 await assert.rejects(()=>db.query('select * from experiments'),/permission denied/);
 await db.exec(`reset role;set role authenticated;select set_config('request.jwt.claim.sub','${stranger}',false)`);
 assert.equal((await db.query('select * from experiments')).rows.length,0);
 await assert.rejects(()=>db.query(`insert into experiments(project_id,id,profile_id,model) values($1,$2,$3,'bad')`,[project,id(99),profile]),/permission denied/);
 await assert.rejects(()=>db.query('select * from upload_credentials'),/permission denied/);
 await db.exec(`select set_config('request.jwt.claim.sub','${owner}',false)`);
 assert.equal((await db.query('select * from experiments')).rows.length,1);
 assert.equal((await db.query('select monitor_run($1,$2) as run',[project,experiment])).rows[0].run.history.length,2);
 assert.equal((await db.query('select monitor_overview($1) as data',[project])).rows[0].data[0].best.action_mt5r,0.4);
 assert.equal((await db.query('select monitor_overview($1) as data',[other])).rows[0].data.length,0);
 await assert.rejects(()=>db.query('select monitor_ingest($1,$2::jsonb)',[credential,JSON.stringify([event('progress',{phase:'bad'})])]),/permission denied/);
 await db.exec('reset role');await db.query('update upload_credentials set revoked_at=now() where id=$1',[credential]);
 await assert.rejects(()=>ingest([event('progress',{phase:'training'})]),/credential_denied/);
 console.log('Postgres migration, atomic ingestion, idempotency, resume projection, RLS and revocation checks passed.');
}finally{await db.close()}
